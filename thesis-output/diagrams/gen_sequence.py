def auth():
    s = Seq("SEQ xác thực", [("u", "Người dùng", "actor"), ("ui", "Giao diện xác thực", "boundary"),
                              ("c", "Điều khiển xác thực", "control"), ("lim", "Bộ giới hạn đăng nhập", "control"),
                              ("tok", "Bộ cấp mã phiên", "control"), ("tk", "Tài khoản", "entity")])
