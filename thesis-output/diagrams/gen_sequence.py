    s.ret("tk", "c")
    s.alt_begin("alt", "email đã tồn tại", ["ui", "tk"])
    s.ret("c", "ui", "thông báo email đã được sử dụng")
    s.alt_else("email chưa tồn tại")
    s.msg("c", "tk", "tạoTàiKhoản(mật khẩu đã băm)")
    s.ret("tk", "c")
    s.ret("c", "ui", "thông báo đăng ký thành công")
    s.self_("ui", "chuyểnTrangĐăngNhập()")
    s.alt_end()
    s.alt_end()
    s.note("u", "Đăng nhập")
    s.msg("u", "ui", "nhập email, mật khẩu")
    s.msg("ui", "c", "gửiYêuCầuĐăngNhập()")
    s.msg("c", "lim", "kiểmTraSốLầnSai(email, IP)")
    s.ret("lim", "c")
    s.alt_begin("alt", "vượt giới hạn", ["ui", "tk"])
    s.ret("c", "ui", "báo lỗi tạm khóa, thời gian chờ")
    s.alt_else("được phép")
    s.msg("c", "tk", "tìmTàiKhoảnTheoEmail()")
    s.ret("tk", "c")
